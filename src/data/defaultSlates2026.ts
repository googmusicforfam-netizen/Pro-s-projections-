  interface RawPlayer {
    id: string;
    name: string;
    team: string;
    opponent: string;
    isHome: boolean;
    position: string;
    eligiblePositions: string[];
    salaryDK: number;
    salaryFD: number;
    projectedPoints: number;
    ceiling: number;
    floor: number;
    projectedOwnership: number;
    gameTime: string;
    status: 'CONFIRMED' | 'PROBABLE' | 'QUESTIONABLE' | 'GTD' | 'OUT' | 'HEALTHY';
    statusNote?: string;
    whyNote: string;
    matchupRating: 'soft' | 'average' | 'tough';
    opponentRank: number;
    matchupDetail: string;
    last3Avg: number;
    seasonAvg: number;
    isHot: boolean;
    isCold: boolean;
  }

  let rawPlayers: RawPlayer[] = [];
  let stacks: SlateStack[] = [];

  if (sport === 'nba') {
    rawPlayers = NBA_PLAYERS_2026 as RawPlayer[];
    stacks = NBA_STACKS_2026 as SlateStack[];
  } else if (sport === 'nfl') {
    rawPlayers = NFL_PLAYERS_2026 as RawPlayer[];
    stacks = NFL_STACKS_2026 as SlateStack[];
  } else if (sport === 'nhl') {
    rawPlayers = NHL_PLAYERS_2026 as RawPlayer[];
    stacks = NHL_STACKS_2026 as SlateStack[];
  } else if (sport === 'nascar') {
    rawPlayers = [];
    stacks = NASCAR_STACKS_2026 as SlateStack[];
  }

  const players = rawPlayers.map((p) => {
    const salary = isFD ? p.salaryFD : p.salaryDK;
    const valueScore = Number((p.projectedPoints / (salary / 1000)).toFixed(2));
    return {
      id: p.id,
      name: p.name,
      team: p.team,
      opponent: p.opponent,
      isHome: p.isHome,
      position: p.position,
      eligiblePositions: p.eligiblePositions,
      salary,
      projectedPoints: p.projectedPoints,
      ceiling: p.ceiling,
      floor: p.floor,
      valueScore,
      projectedOwnership: p.projectedOwnership,
      gameTime: p.gameTime,
      isStarted: false,
      isLocked: false,
      status: p.status,
      statusNote: (p as any).statusNote,
      whyNote: p.whyNote,
      matchupRating: p.matchupRating,
      opponentRank: p.opponentRank,
      matchupDetail: p.matchupDetail,
      last3Avg: p.last3Avg,
      seasonAvg: p.seasonAvg,
      isHot: p.isHot,
      isCold: p.isCold,
    };
  });

  const news = NEWS_FEED_2026.filter((n) => n.sport === sport);

  const highPriorityAlert =
    sport === 'nba'
      ? {
          id: 'alert-beal-out',
          player: 'Bradley Beal',
          team: 'PHX',
          headline: 'Bradley Beal (back tightness) is ruled OUT vs Timberwolves',
          replacementRecommendation:
            'Grayson Allen ($4,800 DK / $5,100 FD) enters top-value tier (6.2x). Devin Booker ceiling rises to 63.5 pts.',
        }
      : undefined;

  return {
    id: `${site}-${sport}-default`,
    dayLabel: 'Tonight (Thu, Nov 5)',
    slateName:
      sport === 'nfl'
        ? 'Jacksonville at Baltimore (1 game, 8:15 PM)'
        : sport === 'nba'
        ? 'Main Slate (5 games, 7:00 PM)'
        : sport === 'nhl'
        ? 'Main Slate (4 games, 7:00 PM)'
        : 'Championship Race (1 race, 3:00 PM)',
    shortLabel: 'Main Slate',
    format: sport === 'nfl' ? (isFD ? 'single_game_mvp' : 'showdown_captain') : 'classic',
    gameCount: sport === 'nfl' ? 1 : sport === 'nba' ? 5 : sport === 'nhl' ? 4 : 1,
    teams: ['BOS', 'PHI', 'MIL', 'NYK', 'PHX', 'MIN', 'DAL', 'GSW', 'DEN', 'LAL'],
    gameSummary: sport === 'nfl' ? 'JAX @ BAL' : '5 Games on Slate',
    status: 'Upcoming',
    isCaptainMode: sport === 'nfl',
    sport,
    sportLabel: sport.toUpperCase(),
    hasGamesToday,
    seasonContext:
      sport === 'nba'
        ? '2026-27 NBA Regular Season'
        : sport === 'nfl'
        ? '2026 NFL Week 10 (Thursday Night Football)'
        : sport === 'nhl'
        ? '2026-27 NHL Regular Season'
        : sport === 'mlb'
        ? '2026 MLB Offseason (World Series Concluded)'
        : 'NASCAR Cup Series (Next Race: Sunday Phoenix Championship)',
    date: '2026-11-05',
    site,
    salaryCap: cap,
    rosterSlots,
    firstGameTime: sport === 'nba' ? '2026-11-05T19:00:00Z' : sport === 'nfl' ? '2026-11-05T20:15:00Z' : '2026-11-05T19:00:00Z',
    lastGameTime: sport === 'nba' ? '2026-11-05T22:30:00Z' : sport === 'nfl' ? '2026-11-05T20:15:00Z' : '2026-11-05T22:00:00Z',
    lastUpdated: new Date().toISOString(),
    sources: [
      'Fantasy Fuel DFS (Salaries & Value Projections)',
      'Official 2026 Injury Wire & Beat Repos',
      'Confirmed Starting Lineups & Rotations',
      'Vegas Consensus Betting Totals & Spreads',
      'StartingGoalies.com (Confirmed NHL Starters)',
    ],
    players,
    stacks,
    news,
    highPriorityAlert,
  };

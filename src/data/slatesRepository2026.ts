// Master Upcoming 7-Day Slates Index Across All Sports
export function getUpcoming7DaySlates(): SlateMeta[] {
  const sports: Sport[] = ['nfl', 'nba', 'nhl', 'nascar'];
  const sites: Site[] = ['draftkings', 'fanduel'];
  const all: SlateMeta[] = [];

  sports.forEach((sport) => {
    sites.forEach((site) => {
      const slates = getAllSlates(sport, site);
      slates.forEach((s) => {
        all.push({
          id: s.id,
          sport: s.sport,
          site: s.site,
          date: s.date,
          dayLabel: s.dayLabel,
          slateName: s.slateName,
          shortLabel: s.shortLabel,
          format: s.format,
          gameCount: s.gameCount,
          firstGameTime: s.firstGameTime,
          lastGameTime: s.lastGameTime,
          teams: s.teams,
          gameSummary: s.gameSummary,
          status: s.status,
          isCaptainMode: s.isCaptainMode,
          salaryCap: s.salaryCap,
          rosterSlots: s.rosterSlots,
        });
      });
    });
  });

  // Sort soonest first
  all.sort((a, b) => new Date(a.firstGameTime).getTime() - new Date(b.firstGameTime).getTime());
  return all;
}
